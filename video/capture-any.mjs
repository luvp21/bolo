import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const { chromium } = require("/home/luv/.npm/_npx/6bcb61ec6d5aea22/node_modules/playwright");
const OUT = `${process.env.V}/shots`, URL = process.env.URL;
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 2 });
await p.goto(`${URL}/tech/new`); await p.waitForTimeout(800);
await p.getByLabel("Topic").fill("How UPI payments work");
await p.screenshot({ path: `${OUT}/any-form.png` });
await p.getByRole("button", { name: "Make my passage" }).click();
await p.waitForTimeout(400); await p.screenshot({ path: `${OUT}/any-writing.png` });
await p.waitForURL(/\/tech\/custom-/, { timeout: 60000 }); await p.waitForTimeout(1500);
await p.screenshot({ path: `${OUT}/any-ladder.png` });
const text = await p.locator("main p.font-serif").first().innerText();
await p.goto(`${URL}/tech`); await p.waitForTimeout(1200);
await p.screenshot({ path: `${OUT}/any-list.png` });
const listed = await p.getByText("Your topics").count();
await b.close();
